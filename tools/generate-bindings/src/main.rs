//! Regenerates `librocksdb-sys/src/bindings.rs` from RocksDB's C API header.
//!
//! Run it from the repository root after updating the `rocksdb` submodule:
//!
//! ```sh
//! cargo run --manifest-path tools/generate-bindings/Cargo.toml --locked
//! ```
//!
//! It needs libclang. The bindings are generated for one fixed target with
//! clang's freestanding headers, so the output does not depend on the host.
//! Only `rocksdb_*` items are emitted, which are the same on every supported
//! target except that MSVC types the 13 anonymous enums as `c_int` instead of
//! `c_uint`. Those types only appear on constants, never in a function
//! signature, so the one file is correct on Windows as well.

use std::{env, path::PathBuf};

const HEADER: &str = "librocksdb-sys/rocksdb/include/rocksdb/c.h";
const OUTPUT: &str = "librocksdb-sys/src/bindings.rs";
const TARGET: &str = "x86_64-unknown-linux-gnu";

fn main() {
    let root = env::args_os()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("."));
    let header = root.join(HEADER);
    let output = root.join(OUTPUT);

    bindgen::Builder::default()
        .header(header.to_str().expect("the header path is UTF-8"))
        .raw_line(
            "// @generated by tools/generate-bindings from rocksdb/include/rocksdb/c.h. Do not edit.",
        )
        .clang_arg(format!("--target={TARGET}"))
        .clang_arg("-ffreestanding")
        .allowlist_function("rocksdb_.*")
        .allowlist_type("rocksdb_.*")
        .allowlist_var("rocksdb_.*")
        // prettyplease is pinned by this tool's lockfile, so the formatting
        // does not depend on which rustfmt the host has.
        .formatter(bindgen::Formatter::Prettyplease)
        .derive_debug(false)
        .ctypes_prefix("libc")
        .size_t_is_usize(true)
        .generate()
        .expect("bindgen generates the RocksDB bindings")
        .write_to_file(&output)
        .expect("the bindings file is writable");

    println!("wrote {}", output.display());
}
